// Doodle categories that shouldn't render a watermark on plain cards because
// the yellow-pages card carries its own artwork.
export function doodleFor(categories?: string[] | null): { name: string; paths: string[] } | null {
  if (!categories || categories.length === 0) return null
  for (const cat of categories) {
    const paths = DOODLES[cat]
    if (paths) return { name: cat, paths }
  }
  return { name: 'Other', paths: DOODLES.Other }
}
